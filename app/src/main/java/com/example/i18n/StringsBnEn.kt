    fun forLang(lang: AppLang): AppStrings = when (lang) {
        AppLang.EN -> english
        AppLang.BN -> bengali
    }

    fun toBengaliDigits(value: Int): String {
        val map = charArrayOf('০', '১', '২', '৩', '৪', '৫', '৬', '৭', '৮', '৯')
        return value.toString().map { ch ->
            if (ch in '0'..'9') map[ch - '0'] else ch
        }.joinToString("")
    }

    private fun formatHour(hour24: Int): String {
        val h = hour24.coerceIn(0, 23)
        val suffix = if (h < 12) "AM" else "PM"
        val display = when {
            h == 0 -> 12
            h > 12 -> h - 12
            else -> h
        }
        return "$display:00 $suffix"
    }
